// Android backup rules: what goes into Auto Backup (Google Drive) and a device-to-device
// transfer. Only the user's own data, which can't be downloaded again: the SQLite folder,
// with nomad.db (chats, history, bookmarks, saved places, course progress, the content
// registry) and the kv-store (settings, the emergency plan and kit), each with its
// -wal/-shm. Everything re-downloadable stays out: content/ (archives, maps, routing packs,
// models, and the index file with the map search index and the emergency points) and the
// unpacked map-assets/. Cloud backup skips an app over 25 MB whole, plan included, so the
// rules list what goes in rather than what stays out: with an <include>, nothing else in
// filesDir goes, and a file a native library drops there (a cache, say) can't push it
// over. No <exclude> for content/: outside every include, lint rejects
// it as fatal ("is not in an included path"). After a restore the app finds its content
// rows without files, as after an iOS restore.
//
// Paths are relative to filesDir (expo-file-system's Paths.document on Android; expo-sqlite
// and src/db keep the databases in filesDir/SQLite). Keep them in step with
// src/lib/storage.ts, src/features/maps/assets.ts and src/db/index.ts.
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const USER_DATA = ['SQLite'];

const BACKUP_RULES = 'nomad_backup_rules';
const EXTRACTION_RULES = 'nomad_data_extraction_rules';

const rules = (indent) => USER_DATA.map((p) => `${indent}<include domain="file" path="${p}" />`).join('\n');

// Android 11 and older (cloud backup and adb).
const backupRules = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-rules.js -->
<full-backup-content>
${rules('  ')}
</full-backup-content>
`;

// Android 12 and newer: cloud backup and device-to-device transfer, the same files.
const extractionRules = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-rules.js -->
<data-extraction-rules>
  <cloud-backup>
${rules('    ')}
  </cloud-backup>
  <device-transfer>
${rules('    ')}
  </device-transfer>
</data-extraction-rules>
`;

function withBackupRuleFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, `${BACKUP_RULES}.xml`), backupRules);
      await fs.promises.writeFile(path.join(dir, `${EXTRACTION_RULES}.xml`), extractionRules);
      return config;
    },
  ]);
}

function withBackupRuleAttributes(config) {
  return withAndroidManifest(config, (config) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(config.modResults);
    app.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
    app.$['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
    return config;
  });
}

module.exports = function withAndroidBackupRules(config) {
  return withBackupRuleAttributes(withBackupRuleFiles(config));
};
