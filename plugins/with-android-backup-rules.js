// Android backup rules. Auto Backup copies the app's files to the user's Google Drive, but an
// app over 25 MB is skipped whole, emergency plan included. The downloaded content and the
// unpacked map assets (gigabytes, all re-downloadable) never go. nomad.db stays out of the
// cloud backup too, although it is small now: the map search indexes live in their own file,
// content/index/search.db, which the content/ rule already covers. Putting nomad.db (saved
// places, chats, bookmarks) back into the cloud backup is an open owner decision
// (docs/PROGRESS.md). What is left is the kv-store (settings, the emergency plan and the kit),
// which fits. A device-to-device transfer has no quota, so it also carries nomad.db; the app
// then finds its content rows without files, as after an iOS restore.
//
// Paths are relative to filesDir (expo-file-system's Paths.document on Android; expo-sqlite
// keeps its databases in filesDir/SQLite). Keep them in step with src/lib/storage.ts,
// src/features/maps/assets.ts and src/db/index.ts.
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const CONTENT = ['content', 'map-assets'];
const DATABASE = ['nomad.db', 'nomad.db-wal', 'nomad.db-shm', 'nomad.db-journal'].map((f) => `SQLite/${f}`);

const BACKUP_RULES = 'nomad_backup_rules';
const EXTRACTION_RULES = 'nomad_data_extraction_rules';

const excludes = (paths, indent) => paths.map((p) => `${indent}<exclude domain="file" path="${p}" />`).join('\n');

// Android 11 and older (cloud backup and adb): one set of rules.
const backupRules = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-rules.js -->
<full-backup-content>
${excludes([...CONTENT, ...DATABASE], '  ')}
</full-backup-content>
`;

// Android 12 and newer: cloud backup and device-to-device transfer separately.
const extractionRules = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-android-backup-rules.js -->
<data-extraction-rules>
  <cloud-backup>
${excludes([...CONTENT, ...DATABASE], '    ')}
  </cloud-backup>
  <device-transfer>
${excludes(CONTENT, '    ')}
  </device-transfer>
</data-extraction-rules>
`;

function withBackupRuleFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, `${BACKUP_RULES}.xml`), backupRules);
      await fs.promises.writeFile(path.join(dir, `${EXTRACTION_RULES}.xml`), extractionRules);
      return config;
    },
  ]);
}

function withBackupRuleAttributes(config) {
  return withAndroidManifest(config, (config) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(config.modResults);
    app.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
    app.$['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
    return config;
  });
}

module.exports = function withAndroidBackupRules(config) {
  return withBackupRuleAttributes(withBackupRuleFiles(config));
};
